package com.feedback.model;

import java.io.Serializable;
import java.util.HashMap;
import java.util.Map;

/**
 * JavaBean encapsulating aggregated feedback statistics for the Admin Dashboard.
 */
public class FeedbackStats implements Serializable {
    private static final long serialVersionUID = 1L;

    private int totalFeedback;
    private double averageRating;
    private int fiveStarCount;
    private int fourStarCount;
    private int threeStarCount;
    private int twoStarCount;
    private int oneStarCount;
    private Map<String, Integer> courseDistribution = new HashMap<>();

    public FeedbackStats() {
    }

    public int getTotalFeedback() {
        return totalFeedback;
    }

    public void setTotalFeedback(int totalFeedback) {
        this.totalFeedback = totalFeedback;
    }

    public double getAverageRating() {
        return averageRating;
    }

    public void setAverageRating(double averageRating) {
        this.averageRating = averageRating;
    }

    public int getFiveStarCount() {
        return fiveStarCount;
    }

    public void setFiveStarCount(int fiveStarCount) {
        this.fiveStarCount = fiveStarCount;
    }

    public int getFourStarCount() {
        return fourStarCount;
    }

    public void setFourStarCount(int fourStarCount) {
        this.fourStarCount = fourStarCount;
    }

    public int getThreeStarCount() {
        return threeStarCount;
    }

    public void setThreeStarCount(int threeStarCount) {
        this.threeStarCount = threeStarCount;
    }

    public int getTwoStarCount() {
        return twoStarCount;
    }

    public void setTwoStarCount(int twoStarCount) {
        this.twoStarCount = twoStarCount;
    }

    public int getOneStarCount() {
        return oneStarCount;
    }

    public void setOneStarCount(int oneStarCount) {
        this.oneStarCount = oneStarCount;
    }

    public Map<String, Integer> getCourseDistribution() {
        return courseDistribution;
    }

    public void setCourseDistribution(Map<String, Integer> courseDistribution) {
        this.courseDistribution = courseDistribution;
    }
}
